"""Make the picture of St. Jean-Marie Vianney that the break reminder shows (needs ImageMagick: `magick`).

The break reminder (extension/src/content/breakcard.js) is drawn like a video or a comment. The only thing that gives it away is the portrait: the
round channel picture, and the thumbnail. The portrait must come with the extension itself and must not be a web-accessible file (YouTube could
see that the file can be loaded), so it is a data URI inside a small script, which this tool writes.

The source is the black-and-white cut of the well-known portrait in assets/vianney-bust.png (public domain, see tools/make-icons.py) and the hand-traced outline of
head and shoulders in assets/vianney-bust-outline.png. The outline becomes the transparency, so what is outside the figure shows the colours behind it (the avatar's circle,
the gradient of the thumbnail) and the black rim that the cut has around the figure stays as a sticker outline. One picture serves for both uses.

Run: python3 tools/make-break-image.py
Writes extension/src/content/vianney-image.js (about 12 KB).
"""
import base64
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUST = ROOT / 'assets' / 'vianney-bust.png'              # 500 x 739, white figure on black
OUTLINE = ROOT / 'assets' / 'vianney-bust-outline.png'   # the same size, white silhouette on black
OUT = ROOT / 'extension' / 'src' / 'content' / 'vianney-image.js'
WIDTH = 280      # 2x of the largest place it is drawn at on a normal screen (the portrait on the thumbnail is about 140 pixels wide)
COLORS = 12      # two tones with the grey of the smoothed edges: more colours only make the file larger


def build(png: Path) -> None:
    subprocess.run([
        'magick', str(BUST), '-colorspace', 'Gray',
        '(', str(OUTLINE), '-colorspace', 'Gray', '-threshold', '50%', ')',
        '-alpha', 'off', '-compose', 'CopyOpacity', '-composite',                     # the outline is the alpha channel
        '-filter', 'Lanczos', '-resize', f'{WIDTH}x',
        '-type', 'TrueColorAlpha', '-colors', str(COLORS), '-type', 'PaletteBilevelAlpha',
        '-define', 'png:compression-level=9', '-define', 'png:exclude-chunk=all', str(png),
    ], check=True)


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / 'vianney.png'
        build(png)
        size = subprocess.run(['magick', 'identify', '-format', '%w %h', str(png)], capture_output=True, text=True, check=True).stdout.split()
        data = base64.b64encode(png.read_bytes()).decode('ascii')
    OUT.write_text(
        '// GENERATED by tools/make-break-image.py from assets/vianney-bust.png and assets/vianney-bust-outline.png: do not edit.\n'
        '// The portrait of St. Jean-Marie Vianney for the break reminder (content/breakcard.js), as a data URI: a file of the extension that a page could load\n'
        '// would have to be listed as web-accessible, and then YouTube could tell that the extension is installed.\n'
        f'export const PORTRAIT_WIDTH = {size[0]};\n'
        f'export const PORTRAIT_HEIGHT = {size[1]};\n'
        f"export const PORTRAIT = 'data:image/png;base64,{data}';\n",
        encoding='utf-8')
    print(f'wrote {OUT.relative_to(ROOT)}: {size[0]} x {size[1]} px, {len(data) * 3 // 4:,} bytes of picture, {OUT.stat().st_size:,} bytes of script')


if __name__ == '__main__':
    main()
