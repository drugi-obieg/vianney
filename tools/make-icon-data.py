"""Turn downloaded Lucide icons into the two places that use them: the settings page and the website.

Lucide (https://lucide.dev, ISC licence) is not a dependency: only the few icons that are used are kept, as plain shape data.
  extension/src/options/icons.js     the settings page builds <svg> elements from this data (no markup is parsed)
  _includes/icon.html                the website includes an icon with {% include icon.html name="download" size=16 %}

Usage:
  mkdir /tmp/lucide && cd /tmp/lucide
  for n in <names>; do curl -sSO https://unpkg.com/lucide-static@0.468.0/icons/$n.svg; done
  curl -sSO https://unpkg.com/lucide-static@0.468.0/LICENSE
  python3 tools/make-icon-data.py /tmp/lucide

The downloaded files are untrusted data: every file must be an <svg> on a 24 by 24 grid that holds nothing but plain shapes with
known attributes, and the output is written from that checked data, never copied from the files. Run with -I semantics in mind:
the script reads them as text only.
"""
import glob
import json
import os
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OPTIONS_OUT = os.path.join(ROOT, 'extension', 'src', 'options', 'icons.js')
OPTIONS_LICENSE = os.path.join(ROOT, 'extension', 'src', 'options', 'LICENSE-icons.txt')
SITE_OUT = os.path.join(ROOT, '_includes', 'icon.html')

# What each place uses. The settings page also falls back to "info" for a name it does not know.
OPTIONS_ICONS = ['book-open', 'captions', 'check', 'chevron-left', 'chevron-right', 'church', 'coffee', 'cpu', 'dices', 'download', 'ear', 'external-link', 'eye-off',
                 'eraser', 'eye', 'flask-conical', 'history', 'image', 'info', 'list-checks', 'message-square-warning', 'play', 'rotate-ccw', 'search',
                 'settings-2', 'shield-check', 'sparkles', 'trash-2', 'triangle-alert', 'users', 'volume-2']
SITE_ICONS = ['sparkles', 'download', 'shield-check', 'church', 'list-checks', 'code-xml', 'external-link', 'chevron-left', 'chevron-right', 'search',
              'eye-off', 'file-text', 'sliders-horizontal', 'ear', 'coffee', 'image', 'lock', 'check', 'info', 'eraser']

SHAPES = {'path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse', 'g'}
ATTRS = {'d', 'cx', 'cy', 'r', 'x', 'y', 'x1', 'x2', 'y1', 'y2', 'rx', 'ry', 'points', 'width', 'height', 'transform'}
NS = '{http://www.w3.org/2000/svg}'


def load(src):
    icons = {}
    for path in sorted(glob.glob(os.path.join(src, '*.svg'))):
        name = os.path.basename(path)[:-4]
        root = ET.parse(path).getroot()
        assert root.tag == NS + 'svg', (name, root.tag)
        assert root.attrib.get('viewBox') == '0 0 24 24', (name, root.attrib.get('viewBox'))
        shapes = []

        def walk(el, out):
            for child in el:
                tag = child.tag.replace(NS, '')
                assert tag in SHAPES, (name, 'unexpected element', tag)
                attrs = {}
                for k, v in child.attrib.items():
                    assert k in ATTRS, (name, tag, 'unexpected attribute', k)
                    low = v.lower()
                    assert 'script' not in low and 'javascript' not in low and 'url(' not in low and '"' not in v and '<' not in v and '{' not in v, (name, k, v)
                    attrs[k] = v
                if tag == 'g':
                    assert not attrs or set(attrs) <= {'transform'}, (name, 'group attrs', attrs)
                    walk(child, out)      # a plain group: its shapes are kept, the group itself carries nothing we need
                else:
                    out.append([tag, attrs])
        walk(root, shapes)
        assert shapes, name
        icons[name] = shapes
    return icons


def options_js(icons):
    subset = {n: icons[n] for n in OPTIONS_ICONS}
    lines = ['// Icons from Lucide (https://lucide.dev), version lucide-static 0.468.0, ISC licence: see LICENSE-icons.txt.',
             '// Only plain shapes (path, circle, rect, line, polyline, polygon, ellipse) were kept; each file was checked for anything else.',
             '// Drawn with currentColor strokes on a 24 by 24 grid, in the style of the macOS settings icons (white on a coloured square).',
             '// Generated by tools/make-icon-data.py: do not edit by hand.',
             '', 'const SHAPES = ' + json.dumps(subset, separators=(',', ':'), sort_keys=True) + ';', '',
             "const NS = 'http://www.w3.org/2000/svg';", '',
             '/** An <svg> element for an icon, built from shape data (no markup is parsed). */',
             'export function icon(name, size = 18) {',
             "  const svg = document.createElementNS(NS, 'svg');",
             "  svg.setAttribute('viewBox', '0 0 24 24');",
             "  svg.setAttribute('width', String(size));",
             "  svg.setAttribute('height', String(size));",
             "  svg.setAttribute('fill', 'none');",
             "  svg.setAttribute('stroke', 'currentColor');",
             "  svg.setAttribute('stroke-width', '2');",
             "  svg.setAttribute('stroke-linecap', 'round');",
             "  svg.setAttribute('stroke-linejoin', 'round');",
             "  svg.setAttribute('aria-hidden', 'true');",
             '  for (const [tag, attrs] of SHAPES[name] || SHAPES.info) {',
             '    const el = document.createElementNS(NS, tag);',
             '    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);',
             '    svg.appendChild(el);',
             '  }',
             '  return svg;',
             '}', '',
             'export const ICON_NAMES = Object.keys(SHAPES);', '']
    return '\n'.join(lines)


def site_include(icons):
    def markup(shapes):
        out = []
        for tag, attrs in shapes:
            out.append('<' + tag + ''.join(f' {k}="{v}"' for k, v in attrs.items()) + '/>')
        return ''.join(out)
    head = ('{%- comment -%}Generated by tools/make-icon-data.py from Lucide (ISC), see assets/LICENSE-icons.txt: do not edit by hand. '
            'Use: include icon.html with the arguments name and size.{%- endcomment -%}\n')
    svg_open = '<svg class="icon" viewBox="0 0 24 24" width="{{ include.size | default: 16 }}" height="{{ include.size | default: 16 }}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    body = ['{%- case include.name -%}']
    for name in SITE_ICONS:
        body.append('{%- when "' + name + '" -%}' + svg_open + markup(icons[name]) + '</svg>')
    body.append('{%- else -%}' + svg_open + markup(icons['info']) + '</svg>')
    body.append('{%- endcase -%}')
    return head + '\n'.join(body) + '\n'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    icons = load(src)
    for n in set(OPTIONS_ICONS) | set(SITE_ICONS):
        assert n in icons, f'missing {n}.svg in {src}'
    licence = open(os.path.join(src, 'LICENSE'), encoding='utf-8').read()
    with open(OPTIONS_OUT, 'w', encoding='utf-8') as f:
        f.write(options_js(icons))
    os.makedirs(os.path.dirname(SITE_OUT), exist_ok=True)
    with open(SITE_OUT, 'w', encoding='utf-8') as f:
        f.write(site_include(icons))
    text = ('The icons in extension/src/options/icons.js and _includes/icon.html are from Lucide (https://lucide.dev), package lucide-static 0.468.0.\n'
            'Lucide is released under the ISC licence, which reads:\n\n' + licence)
    for path in (OPTIONS_LICENSE, os.path.join(ROOT, 'assets', 'LICENSE-icons.txt')):
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
    print(f'icons for the settings page: {len(OPTIONS_ICONS)}, for the site: {len(SITE_ICONS)}; '
          f'{os.path.getsize(OPTIONS_OUT)} and {os.path.getsize(SITE_OUT)} bytes')


if __name__ == '__main__':
    main()
